import 'load_profile.dart';

/// Reference to one entry in the request sequence a performance test repeats.
///
/// Only the stable request id and display name are stored so results stay
/// portable across collections and environments.
class PerfRequestRef {
  const PerfRequestRef({required this.id, required this.name, this.method});

  final String id;
  final String name;

  /// HTTP method when the sequence entry is an HTTP request; `null` for
  /// other request kinds (MQTT, WebSocket, ...).
  final String? method;

  Map<String, Object?> toJson() => {
    'id': id,
    'name': name,
    if (method != null) 'method': method,
  };

  factory PerfRequestRef.fromJson(Map<String, Object?> json) {
    return PerfRequestRef(
      id: json['id'] as String? ?? '',
      name: json['name'] as String? ?? '',
      method: json['method'] as String?,
    );
  }

  @override
  String toString() => 'PerfRequestRef(${toJson()})';
}

/// Serializable description of how a performance test run was configured.
///
/// Embedded inside [PerfRunResults] so an imported results file is
/// self-describing: the dashboard can show exactly which collection,
/// sequence, virtual user count, duration and load profile produced it.
class PerfRunConfig {
  const PerfRunConfig({
    required this.runId,
    required this.startedAt,
    required this.requestSequence,
    required this.virtualUsers,
    required this.durationSeconds,
    required this.loadProfile,
    this.collectionName,
    this.baseUrl,
  });

  /// Unique identifier of the run, generated by the CLI or app.
  final String runId;

  /// Wall-clock time the run started (UTC recommended).
  final DateTime startedAt;

  /// Display name of the collection the sequence was taken from, if any.
  final String? collectionName;

  /// Ordered request sequence each virtual user repeats.
  final List<PerfRequestRef> requestSequence;

  /// Configured virtual user count.
  final int virtualUsers;

  /// Planned test duration in seconds.
  final int durationSeconds;

  /// Load profile applied on top of [virtualUsers]/[durationSeconds].
  final PerfLoadProfile loadProfile;

  /// Optional target base URL, for context when visualizing results.
  final String? baseUrl;

  Map<String, Object?> toJson() => {
    'runId': runId,
    'startedAt': startedAt.toUtc().toIso8601String(),
    if (collectionName != null) 'collectionName': collectionName,
    'requestSequence': requestSequence.map((r) => r.toJson()).toList(),
    'virtualUsers': virtualUsers,
    'durationSeconds': durationSeconds,
    'loadProfile': loadProfile.toJson(),
    if (baseUrl != null) 'baseUrl': baseUrl,
  };

  factory PerfRunConfig.fromJson(Map<String, Object?> json) {
    final sequenceJson = json['requestSequence'];
    return PerfRunConfig(
      runId: json['runId'] as String? ?? '',
      startedAt:
          DateTime.tryParse(json['startedAt'] as String? ?? '')?.toUtc() ??
          DateTime.fromMillisecondsSinceEpoch(0, isUtc: true),
      collectionName: json['collectionName'] as String?,
      requestSequence: sequenceJson is List
          ? sequenceJson
                .whereType<Map<String, Object?>>()
                .map(PerfRequestRef.fromJson)
                .toList()
          : const [],
      virtualUsers: (json['virtualUsers'] as num?)?.toInt() ?? 0,
      durationSeconds: (json['durationSeconds'] as num?)?.toInt() ?? 0,
      loadProfile: json['loadProfile'] is Map<String, Object?>
          ? PerfLoadProfile.fromJson(
              json['loadProfile'] as Map<String, Object?>,
            )
          : const PerfLoadProfile(type: PerfLoadProfileType.fixed),
      baseUrl: json['baseUrl'] as String?,
    );
  }

  @override
  String toString() => 'PerfRunConfig(${toJson()})';
}
